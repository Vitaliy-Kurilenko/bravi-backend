-- Store-scoped catalog: manufacturers, categories, products, product images + global stock statuses.

CREATE TABLE manufacturers
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    store_id    BIGINT       NOT NULL,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    status      VARCHAR(32)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_manufacturers PRIMARY KEY (id),
    CONSTRAINT uq_manufacturers_store_name UNIQUE (store_id, name)
);

ALTER TABLE manufacturers
    ADD CONSTRAINT fk_manufacturers_on_store FOREIGN KEY (store_id) REFERENCES stores (id);
CREATE INDEX idx_manufacturers_store_id ON manufacturers (store_id);


CREATE TABLE categories
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    store_id    BIGINT       NOT NULL,
    parent_id   BIGINT,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    status      VARCHAR(32)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_categories PRIMARY KEY (id)
);

ALTER TABLE categories
    ADD CONSTRAINT fk_categories_on_store FOREIGN KEY (store_id) REFERENCES stores (id);
ALTER TABLE categories
    ADD CONSTRAINT fk_categories_on_parent FOREIGN KEY (parent_id) REFERENCES categories (id);
CREATE INDEX idx_categories_store_id ON categories (store_id);
CREATE INDEX idx_categories_parent_id ON categories (parent_id);
CREATE UNIQUE INDEX uq_categories_root_name
    ON categories (store_id, name) WHERE parent_id IS NULL;
CREATE UNIQUE INDEX uq_categories_child_name
    ON categories (store_id, parent_id, name) WHERE parent_id IS NOT NULL;


CREATE TABLE stock_statuses
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code VARCHAR(64)  NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT pk_stock_statuses PRIMARY KEY (id),
    CONSTRAINT uq_stock_statuses_code UNIQUE (code)
);

